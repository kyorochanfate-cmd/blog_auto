def apply_preset(blog, preset_key):
    """preset_keyが指定されていればtone_prompt/article_policyを上書き、なければblogのものを返す。

    戻り値: (tone_prompt, article_policy)
    """
    if not preset_key or preset_key == 'blog_default':
        return blog.get('tone_prompt', ''), blog.get('article_policy', '')
    p = PRESETS.get(preset_key)
    if not p:
        return blog.get('tone_prompt', ''), blog.get('article_policy', '')
    return p['tone_prompt'], p['article_policy']
